-- Section 1: Database Schema Creation

-- Create Users table
CREATE TABLE users (
    user_id       NUMBER PRIMARY KEY,
    name          VARCHAR2(50) NOT NULL,
    email         VARCHAR2(100) UNIQUE NOT NULL,
    city          VARCHAR2(50),
    reg_date      DATE DEFAULT SYSDATE
);

-- Create Restaurants table
CREATE TABLE restaurants (
    restaurant_id NUMBER PRIMARY KEY,
    name          VARCHAR2(100) NOT NULL,
    cuisine       VARCHAR2(50),
    city          VARCHAR2(50),
    rating        NUMBER(2, 1)
);

-- Create Orders table
-- Links users and restaurants using foreign keys
CREATE TABLE orders (
    order_id      NUMBER PRIMARY KEY,
    user_id       NUMBER REFERENCES users(user_id),
    restaurant_id NUMBER REFERENCES restaurants(restaurant_id),
    order_date    DATE NOT NULL,
    total_amount  NUMBER(8, 2),
    order_status  VARCHAR2(20) CHECK (order_status IN ('DELIVERED', 'CANCELLED'))
);

-- Create Order Details table
-- Stores individual food items included in each order
CREATE TABLE order_details (
    order_detail_id NUMBER PRIMARY KEY,
    order_id        NUMBER REFERENCES orders(order_id),
    item_name       VARCHAR2(100),
    quantity        NUMBER DEFAULT 1,
    price_per_item  NUMBER(6, 2)
);


